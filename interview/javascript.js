// Что такое замыкание (Closure)?
// 👉 Функция, которая "запоминает" переменные из своей внешней области.

function counter() {
  let count = 0;
  return () => count++;
}
const increment = counter();
console.log(increment()); // 0
console.log(increment()); // 1

