// 8️⃣ Методы массива: .map(), .filter(), .reduce()
// 👉 .map(fn) — создаёт новый массив, применяя функцию к каждому элементу.
// 👉 .filter(fn) — оставляет только элементы, удовлетворяющие условию.
// 👉 .reduce(fn, acc) — сворачивает массив в одно значение.

const arr = [1, 2, 3, 4];
console.log(arr.map((x) => x * 2)); // [2, 4, 6, 8]
console.log(arr.filter((x) => x % 2 === 0)); // [2, 4]
console.log(arr.reduce((sum, x) => sum + x, 0)); // 10

