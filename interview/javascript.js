// Что такое event loop?
// 👉 Механизм, который позволяет JavaScript выполнять асинхронные задачи.
// 👉 Сначала выполняется синхронный код, потом задачи из callback queue.

// Сначала JS выполняет синхронный код
// Всё, что не асинхронное, кладётся в Call Stack (стек) и выполняется.
// Асинхронные задачи идут в очереди
// Microtasks (микротаски): Promise.then, queueMicrotask
// Macrotasks (макротаски): setTimeout, setInterval, события DOM
// Event Loop следит за стеком
// Если стек пуст, Event Loop переносит задачи из очереди в стек и выполняет их.
// Microtasks выполняются перед макротасками

console.log("Start");
setTimeout(() => console.log("Timeout"), 0);
console.log("End");
// Выведет: Start → End → Timeout

