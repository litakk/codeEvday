// Функции в JavaScript ?

// Function Declaration
// Объявляется через ключевое слово function
// Поднимается (hoisting) — можно вызывать до объявления
function greet() {
  console.log("Hello");
}

// Function Expression
// Функция, присвоенная переменной
// Не всплывает — нельзя вызвать до объявления
const greet2 = function () {
  console.log("Hi");
};

// Arrow Function
// Короткий синтаксис
// Не имеет собственного this, и new
// this берётся из внешнего контекста
const greet3 = () => {
  console.log("Hey");
};

